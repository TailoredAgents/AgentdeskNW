import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import type {Bootstrap} from '../src/lib/contracts';
import type {BillingAdminState,BillingState,SubscriptionRecord} from '../src/lib/billing-contracts';
import type {WalletQuote,WalletState} from '../src/lib/wallet-contracts';
import type {ProviderStatus} from '../src/lib/provider-contracts';

const base=process.env.SMOKE_BASE_URL||'http://127.0.0.1:3000';
const runId=`wallet-smoke-${randomUUID()}`;
let cookie='',checks=0,sequence=0;
const eventKey=(label:string)=>`${runId}-${label}-${++sequence}`;
async function request<T>(path:string,method='GET',value?:unknown,expected=200):Promise<T>{
 const response=await fetch(`${base}/api/${path}`,{method,headers:{Cookie:cookie,'Content-Type':'application/json','X-AgentDesk-Request':'1'},body:value===undefined?undefined:JSON.stringify(value)});
 const session=response.headers.get('set-cookie');if(session)cookie=session.split(';')[0];
 const text=await response.text();assert.equal(response.status,expected,`${method} ${path}: ${text}`);checks++;return text?JSON.parse(text) as T:undefined as T;
}
function check(condition:unknown,message:string){assert.ok(condition,message);checks++;}
const wallet=()=>request<WalletState>('wallet');
const billing=()=>request<BillingState>('billing');
const estimate=(scenarioId:string)=>request<WalletQuote>('wallet/estimate','POST',{scenarioId});
const grantCount=(state:WalletState)=>state.ledger.filter(entry=>entry.kind==='monthly_credit').length;

// Compiled-server acceptance with a disposable database. No payments, outbound transports or AI requests.
await request('wallet','GET',undefined,401);
const initial=await request<Bootstrap>('bootstrap');
check(!initial.integrations.openai&&!initial.integrations.voice,'Live AI must be disabled');
const employeeCookie=cookie;
const initialBilling=await billing();
check(initialBilling.subscription.selection.planId==='workforce'&&initialBilling.quote.personalCents===5000,'Default workforce costs a proposed $50 personally');
check(initialBilling.catalog.find(product=>product.id==='workforce')?.features.length===16,'Workforce includes all sixteen specialist definitions');
check(initialBilling.access.filter(access=>access.implementation==='planned').every(access=>!access.allowed),'Planned specialists remain unavailable');
let state=await wallet();
check(state.availableCents===1500&&state.includedCents===1500&&state.purchasedCents===0,'Wallet starts with one $15 monthly grant');
assert.equal(state.mode,'demonstration');assert.equal(state.liveUsageDebiting,false);
const firstVersion=state.version;
const repeated=await wallet();assert.equal(repeated.version,firstVersion);check(grantCount(repeated)===1,'Repeated reads cannot grant another monthly allowance');
await request('billing/quote','POST',{planId:'workforce-enterprise',addons:[]},403);
await request('billing/enterprise-seat','POST',{userId:initial.actor.id,enabled:true,agreementLabel:'Unapproved employee request',expectedVersion:initialBilling.subscription.version,eventKey:eventKey('employee-company-seat')},403);
await request('wallet/topup','POST',{amountCents:999,expectedVersion:state.version,eventKey:eventKey('invalid-amount')},400);
await request('wallet/topup','POST',{amountCents:1000,userId:'user-jordan',expectedVersion:state.version,eventKey:eventKey('foreign-owner')},400);

const topup={amountCents:1000,expectedVersion:state.version,eventKey:eventKey('topup')};
state=await request<WalletState>('wallet/topup','POST',topup);
check(state.availableCents===2500&&state.purchasedCents===1000,'Simulated top-up adds exactly $10 purchased credits');
const topupReplay=await request<WalletState>('wallet/topup','POST',topup);
assert.equal(topupReplay.version,state.version);assert.equal(topupReplay.availableCents,state.availableCents);
check(topupReplay.ledger.filter(entry=>entry.kind==='topup').length===1,'Top-up replay adds no duplicate ledger entry');
await request('wallet/topup','POST',{...topup,amountCents:2500},409);
await request('wallet/settings','POST',{monthlySpendLimitCents:3000,expectedVersion:firstVersion,eventKey:eventKey('stale-settings')},409);
await request('wallet/settings','POST',{monthlySpendLimitCents:3000,expectedVersion:state.version,eventKey:eventKey('fake-payer'),userId:'user-jordan'},400);

const briefing=await estimate('relationship-briefing');
assert.equal(briefing.costBasis,'fictional_sample');assert.equal(briefing.markupMultiplier,5);
check(briefing.maximumCents===briefing.sampleProviderMaximumCents*5,'Sample estimate snapshots the five-times multiplier');
const beforeReservation=state.availableCents;
const reserve={quoteId:briefing.id,outcome:'reserve',expectedVersion:state.version,eventKey:eventKey('reserve')};
state=await request<WalletState>('wallet/simulate','POST',reserve);
const pending=state.operations.find(operation=>operation.quoteId===briefing.id)!;assert.ok(pending);
check(state.reservedCents===briefing.maximumCents&&state.availableCents===beforeReservation-briefing.maximumCents,'Approved maximum is held before sample work settles');
assert.equal(pending.status,'reserved');assert.equal(pending.chargedCents,0);
check(state.purchasedCents===1000,'Monthly credits are reserved before purchased credits');
const reserveReplay=await request<WalletState>('wallet/simulate','POST',reserve);assert.equal(reserveReplay.operations.length,state.operations.length);assert.equal(reserveReplay.version,state.version);
const finish={operationId:pending.id,outcome:'success',expectedVersion:state.version,eventKey:eventKey('finish')};
state=await request<WalletState>('wallet/resolve','POST',finish);
check(state.reservedCents===0&&state.availableCents===beforeReservation-briefing.successCents,'Settlement consumes the sample amount and releases unused reservation');
assert.equal(state.spentThisPeriodCents,briefing.successCents);
const finishReplay=await request<WalletState>('wallet/resolve','POST',finish);assert.equal(finishReplay.version,state.version);assert.equal(finishReplay.spentThisPeriodCents,state.spentThisPeriodCents);
await request('wallet/resolve','POST',{...finish,expectedVersion:state.version,eventKey:eventKey('finish-again')},409);
await request('wallet/simulate','POST',{quoteId:briefing.id,outcome:'success',expectedVersion:state.version,eventKey:eventKey('reuse-quote')},409);

const research=await estimate('investor-research');
const beforeUnknown=state.availableCents;
state=await request<WalletState>('wallet/simulate','POST',{quoteId:research.id,outcome:'unknown',expectedVersion:state.version,eventKey:eventKey('unknown')});
const unknown=state.operations.find(operation=>operation.quoteId===research.id)!;
check(unknown.status==='unknown'&&state.reservedCents===research.maximumCents,'Uncertain sample result retains its hold');
assert.equal(state.availableCents,beforeUnknown-research.maximumCents);
const privateQuote=await estimate('reply-draft');
await request('session','POST',{role:'acquisitions'});
const otherState=await wallet();
check(otherState.availableCents===1500&&otherState.operations.length===0,'Another employee sees a separate wallet');
await request('wallet/simulate','POST',{quoteId:privateQuote.id,outcome:'success',expectedVersion:otherState.version,eventKey:eventKey('foreign-quote')},404);
await request('wallet/resolve','POST',{operationId:unknown.id,outcome:'cancel',expectedVersion:otherState.version,eventKey:eventKey('foreign-operation')},404);
check((await wallet()).availableCents===1500,'Foreign estimate and operation attempts do not spend another employee’s balance');
cookie=employeeCookie;
state=await wallet();
state=await request<WalletState>('wallet/resolve','POST',{operationId:unknown.id,outcome:'cancel',expectedVersion:state.version,eventKey:eventKey('cancel-unknown')});
check(state.availableCents===beforeUnknown&&state.reservedCents===0,'Confirmed cancellation restores the unknown sample hold');
const cancelQuote=await estimate('reply-draft');
const beforeCancel=state.availableCents;
state=await request<WalletState>('wallet/simulate','POST',{quoteId:cancelQuote.id,outcome:'cancel',expectedVersion:state.version,eventKey:eventKey('cancel-sample')});
check(state.availableCents===beforeCancel&&state.operations.find(operation=>operation.quoteId===cancelQuote.id)?.status==='released','Canceled sample leaves no consumption');

state=await request<WalletState>('wallet/settings','POST',{monthlySpendLimitCents:state.spentThisPeriodCents+40,expectedVersion:state.version,eventKey:eventKey('lower-cap')});
assert.equal(state.spendRemainingCents,40);
const limitedQuote=await estimate('reply-draft');
await request('wallet/simulate','POST',{quoteId:limitedQuote.id,outcome:'success',expectedVersion:state.version,eventKey:eventKey('over-cap')},402);
await request('wallet/settings','POST',{monthlySpendLimitCents:state.spentThisPeriodCents-1,expectedVersion:state.version,eventKey:eventKey('below-spent')},409);
state=await request<WalletState>('wallet/settings','POST',{monthlySpendLimitCents:2500,expectedVersion:state.version,eventKey:eventKey('restore-cap')});
check(state.availableCents===beforeCancel,'Changing a spending cap never purchases credits or changes the balance');

await request('session','POST',{role:'manager'});
const managerCookie=cookie;
const managerWallet=await wallet();check(managerWallet.operations.length===0,'Manager’s personal wallet does not expose employee activity');
let seats=await request<BillingAdminState>('billing/admin');
let employee=seats.seats.find(seat=>seat.userId===initial.actor.id)!;assert.ok(employee);
const assignment={userId:employee.userId,enabled:true,agreementLabel:'Fictional New Western wallet acceptance',expectedVersion:employee.version,eventKey:eventKey('assign-company')};
const assigned=await request<SubscriptionRecord>('billing/enterprise-seat','POST',assignment);
const assignedReplay=await request<SubscriptionRecord>('billing/enterprise-seat','POST',assignment);assert.equal(assignedReplay.version,assigned.version);
cookie=employeeCookie;
const companyBilling=await billing();
check(companyBilling.enterpriseSeat?.active&&companyBilling.quote.organizationCents===3000&&companyBilling.quote.personalCents===0,'Assigned company seat bills a proposed $30 company share and no personal base');
state=await wallet();check(state.availableCents===beforeCancel&&grantCount(state)===1,'Changing the plan within a period does not refill the wallet');
await request('billing/lifecycle','POST',{action:'cancel_now',expectedVersion:companyBilling.subscription.version,eventKey:eventKey('self-cancel-company')},403);
const carryQuote=await estimate('reply-draft');
state=await request<WalletState>('wallet/simulate','POST',{quoteId:carryQuote.id,outcome:'reserve',expectedVersion:state.version,eventKey:eventKey('carry-hold')});
const carryHold=state.operations.find(operation=>operation.quoteId===carryQuote.id)!;assert.ok(carryHold);
const priorPeriod=state.periodStart;
cookie=managerCookie;
await request('billing/lifecycle','POST',{userId:initial.actor.id,action:'renew',expectedVersion:companyBilling.subscription.version,eventKey:eventKey('renew-company')});
cookie=employeeCookie;
state=await wallet();
check(state.periodStart!==priorPeriod&&state.includedCents===1500&&state.purchasedCents===1000,'Renewal refreshes monthly credits once and rolls purchased credits forward');
check(grantCount(state)===2&&state.reservedCents===carryQuote.maximumCents,'Previous-period hold remains pending after monthly refresh');
state=await request<WalletState>('wallet/resolve','POST',{operationId:carryHold.id,outcome:'success',expectedVersion:state.version,eventKey:eventKey('finish-old-hold')});
check(state.availableCents===2500&&state.reservedCents===0,'Finishing an old monthly hold does not credit its unused amount into the new period');
check(state.ledger.some(entry=>entry.operationId===carryHold.id&&entry.expiredCents===carryQuote.maximumCents-carryQuote.successCents),'Unused expired monthly hold is explicitly recorded');

cookie=managerCookie;
seats=await request<BillingAdminState>('billing/admin');employee=seats.seats.find(seat=>seat.userId===initial.actor.id)!;
await request('billing/enterprise-seat','POST',{userId:initial.actor.id,enabled:false,agreementLabel:'End fictional assignment',expectedVersion:employee.version,eventKey:eventKey('remove-company')});
cookie=employeeCookie;
let personalBilling=await billing();
check(personalBilling.subscription.status==='canceled'&&personalBilling.subscription.selection.planId==='workforce','Company removal requires explicit personal resumption');
state=await wallet();check(!state.canSpend&&!state.canTopUp&&state.availableCents===2500,'Inactive subscription preserves wallet balance/history without new spending');
await request('wallet/topup','POST',{amountCents:1000,expectedVersion:state.version,eventKey:eventKey('inactive-topup')},402);
await request('billing/lifecycle','POST',{action:'resume',expectedVersion:personalBilling.subscription.version,eventKey:eventKey('resume-personal')});
personalBilling=await billing();state=await wallet();
check(personalBilling.quote.personalCents===5000&&personalBilling.quote.organizationCents===0,'Explicit personal resumption restores the proposed $50 retail plan');
check(state.canSpend&&state.availableCents===2500&&grantCount(state)===2,'Same-period personal resumption does not grant another monthly refill');
const final=await request<Bootstrap>('bootstrap');
assert.deepEqual(final.investors,initial.investors);assert.equal(final.tasks.length,initial.tasks.length);assert.equal(final.approvals.length,initial.approvals.length);
check((await request<ProviderStatus>('providers')).usage.operations===0,'Wallet demonstration performs no live AI provider work');
console.info(`PASS: ${checks} wallet HTTP checks. Workforce pricing/permissions; monthly grant and simulated top-ups; replay/stale protection; scoped estimates, holds, settlement and cancellation; uncertain outcomes; spending caps; private wallets; company seat assignment/removal; renewal and old-hold reconciliation. No payments, investor messages or AI provider calls.`);
