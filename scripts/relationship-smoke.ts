import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import type {Bootstrap,ToolResult} from '../src/lib/contracts';
import type {InvestorIntelligence} from '../src/lib/intelligence-contracts';
import type {InvestorJourney,InvestorNextStep} from '../src/lib/journey-contracts';
import type {RelationshipRecord,RelationshipReportInput} from '../src/lib/relationship-record-contracts';
import type {WalletState} from '../src/lib/wallet-contracts';
import type {ProviderStatus} from '../src/lib/provider-contracts';

const base=process.env.SMOKE_BASE_URL||'http://127.0.0.1:3000';
let cookie='',checks=0;
async function request<T>(path:string,method='GET',value?:unknown,expected=200):Promise<T>{
 const response=await fetch(base+'/api/'+path,{method,headers:{Cookie:cookie,'Content-Type':'application/json','X-AgentDesk-Request':'1'},body:value===undefined?undefined:JSON.stringify(value)});
 const session=response.headers.get('set-cookie');if(session)cookie=session.split(';')[0];
 const body=await response.text();assert.equal(response.status,expected,method+' '+path+': '+body);checks++;return body?JSON.parse(body) as T:undefined as T;
}
function check(condition:unknown,message:string){assert.ok(condition,message);checks++;}
const path='investors/investor-mike/relationship-record';
await request(path,'GET',undefined,401);
await request(path+'/reports','POST',{},401);
const initial=await request<Bootstrap>('bootstrap'),employeeCookie=cookie;
check(!initial.integrations.openai&&!initial.integrations.voice,'No provider configuration in isolated acceptance');
const walletBefore=await request<WalletState>('wallet');
const original=await request<InvestorIntelligence>('investors/investor-mike/intelligence');
let record=await request<RelationshipRecord>(path);
check(record.reports.length===0&&record.conflicts.length===0&&record.canEdit,'Empty report ledger projects existing criteria');
const budget=record.facts.find(f=>f.topic==='budget');assert.ok(budget?.buyBoxId);
const input:RelationshipReportInput={investorId:'investor-mike',topic:'budget',buyBoxId:budget.buyBoxId,value:{min:120000,max:240000},statement:'Fictional call: Mike reported a lower purchase budget yesterday.',statedAt:new Date(Date.now()-86400000).toISOString(),supersedesId:null,expectedVersion:record.version,expectedContext:record.contextVersion,eventKey:randomUUID()};
await request(path+'/reports','POST',{...input,investorId:'investor-sarah'},400);
await request(path+'/reports','POST',{...input,ownerId:'another-employee'},400);
await request(path+'/reports','POST',{...input,value:{min:300000,max:200000}},400);
const csrf=await fetch(base+'/api/'+path+'/reports',{method:'POST',headers:{Cookie:cookie,'Content-Type':'application/json',Origin:'https://unrelated.example'},body:JSON.stringify(input)});
check(csrf.status===403,'Cross-origin mutations rejected');
record=await request<RelationshipRecord>(path+'/reports','POST',input,201);
check(record.version===1&&record.reports[0].verification==='employee_reported','Reviewed testimony is explicitly reported, not verified');
check(record.conflicts[0].recorded?.displayValue.includes('320,000')&&record.conflicts[0].reports[0].displayValue.includes('240,000'),'Both differing budgets remain available');
assert.deepEqual(await request<InvestorIntelligence>('investors/investor-mike/intelligence'),original);checks++;
const replay=await request<RelationshipRecord>(path+'/reports','POST',input,201);
check(replay.reports.length===1&&replay.reports[0].id===record.reports[0].id,'Exact retry creates no duplicate');
await request(path+'/reports','POST',{...input,statement:'Changed payload with a reused request key'},409);
await request(path+'/reports','POST',{...input,eventKey:randomUUID()},409);
const journey=await request<InvestorJourney>('investors/investor-mike/journey');
check(journey.record.version===1&&journey.evidence.some(e=>e.sourceRecordId===record.reports[0].id),'Journey and record expose the same source');
const next=await request<InvestorNextStep>('investors/investor-mike/recommendation','POST',{propertyId:null});
check(next.action.kind==='clarify_qualification'&&next.draft?.includes('purchase budget')&&next.deliveryStatus==='not_sent','Recommendation asks for clarification without sending');
const chatted=await request<{result:ToolResult}>('chat','POST',{message:'Show Mike investor journey',requestId:randomUUID()});
check(chatted.result.message.includes('purchase budget')&&chatted.result.message.includes('240,000'),'Typed Copilot explains the same differing report');
const correction={...input,value:{min:150000,max:320000},statement:'Correction: the originally recorded budget is still accurate.',statedAt:null,supersedesId:record.reports[0].id,expectedVersion:record.version,expectedContext:record.contextVersion,eventKey:randomUUID()};
record=await request<RelationshipRecord>(path+'/reports','POST',correction,201);
check(record.reports.length===2&&record.reports[0].status==='superseded'&&record.reports[0].statement===input.statement,'Correction preserves its original');
check(record.conflicts.length===0&&record.reports[1].statedAt===null,'Active replacement resolves difference, leaving unknown statement time unknown');
const correctedReplay=await request<RelationshipRecord>(path+'/reports','POST',input,201);
check(correctedReplay.reports.length===2&&correctedReplay.reports[0].status==='superseded','Old exact retries do not undo corrections');
await request('session','POST',{role:'manager'});
check((await request<RelationshipRecord>(path)).reports.length===2,'Authorized office manager can read shared testimony');
await request('session','POST',{role:'acquisitions'});
await request(path,'GET',undefined,404);
await request(path+'/reports','POST',input,403);
cookie=employeeCookie;
const walletAfter=await request<WalletState>('wallet'),providers=await request<ProviderStatus>('providers');
check(walletAfter.availableCents===walletBefore.availableCents&&walletAfter.spentThisPeriodCents===walletBefore.spentThisPeriodCents,'No wallet charge');
check(providers.usage.operations===0,'No model operation');
console.info('PASS: '+checks+' relationship-record HTTP checks. Reviewed report, exact retry, correction, stale review, unchanged CRM, scoped access and Copilot parity; no provider or delivery operation.');
